/**
 * Shared types for the Interesting Finds pipeline.
 *
 * This module is the single contract between lanes: ingest (W2), the crawler
 * (W4), scoring (W5), the digest (W6) and the site page (W7) all speak these
 * shapes. W3 owns the file; other lanes propose changes through the
 * coordinator. Every type here mirrors a table in supabase/migrations, and the
 * migration is the authority -- if the two disagree, the SQL is right.
 *
 * Convention: `Row` types are what the database hands back (timestamps are ISO
 * strings, as PostgREST returns them). `New*` types are what a writer supplies,
 * omitting anything the database fills in.
 */

/** ISO 8601 timestamp string, as PostgREST serialises TIMESTAMPTZ. */
export type Timestamp = string;

/* ========================================================================== */
/* sources                                                                     */
/* ========================================================================== */

/**
 * How we authenticate to a source. `session_cookie` is credential replay and
 * is expected to expire -- see DECISIONS D3.
 */
export type SourceAuthKind =
  | 'none'
  | 'public_api'
  | 'api_key'
  | 'oauth'
  | 'session_cookie';

/**
 * Computed source status. The point of `down` is that it is distinguishable
 * from "found nothing today": an expired Peerlist cookie must be reported, not
 * absorbed into an empty result.
 */
export type SourceStatus = 'ok' | 'stale' | 'down' | 'disabled';

/** A row of `finds_sources`. Private: readable only with the service role. */
export interface SourceRow {
  id: string;
  slug: string;
  display_name: string;
  homepage_url: string;
  enabled: boolean;
  auth_kind: SourceAuthKind;
  /** Known expiry of the credential. `null` means unknown, never means valid. */
  credential_expires_at: Timestamp | null;
  last_attempt_at: Timestamp | null;
  last_success_at: Timestamp | null;
  /** Verbatim failure reason. Never a credential. */
  last_error: string | null;
  last_error_at: Timestamp | null;
  consecutive_failures: number;
  /** No success inside this window makes the source `stale`. */
  staleness_budget_hours: number;
  created_at: Timestamp;
  updated_at: Timestamp;
}

export type NewSource = Pick<SourceRow, 'slug' | 'display_name' | 'homepage_url'> &
  Partial<Pick<SourceRow, 'enabled' | 'auth_kind' | 'credential_expires_at' | 'staleness_budget_hours'>>;

/** A row of the `finds_source_health` view. */
export interface SourceHealthRow {
  id: string;
  slug: string;
  display_name: string;
  status: SourceStatus;
  last_success_at: Timestamp | null;
  last_attempt_at: Timestamp | null;
  last_error: string | null;
  last_error_at: Timestamp | null;
  consecutive_failures: number;
  credential_expires_at: Timestamp | null;
}

/* ========================================================================== */
/* candidates                                                                  */
/* ========================================================================== */

/**
 * Work-queue marker on a candidate. Not a second copy of the truth -- what
 * actually happened to a candidate is the rows in the crawl-verdict, evidence
 * and verdict tables. This exists so a cron run can find its next batch.
 */
export type CandidateStatus =
  | 'new'
  | 'gate_blocked'
  | 'crawled'
  | 'scored'
  | 'digested'
  | 'published'
  | 'rejected';

/** A row of `finds_candidates`. Private. */
export interface CandidateRow {
  id: string;
  /** The product website as first reported, verbatim. */
  product_url: string;
  /**
   * The cross-source dedupe key, GENERATED by the database from product_url
   * via `finds_normalize_url()`. Never write this -- Postgres rejects it.
   */
  canonical_url: string;
  name: string;
  tagline: string | null;
  first_seen_at: Timestamp;
  last_seen_at: Timestamp;
  status: CandidateStatus;
  created_at: Timestamp;
  updated_at: Timestamp;
}

/**
 * What a connector supplies. `canonical_url` is absent on purpose: it is a
 * generated column, so normalisation cannot be forgotten or disagreed about.
 * Upsert with `ON CONFLICT (canonical_url) DO UPDATE SET last_seen_at = NOW()`.
 */
export type NewCandidate = Pick<CandidateRow, 'product_url' | 'name'> &
  Partial<Pick<CandidateRow, 'tagline'>>;

/** A row of `finds_candidate_sightings`: one platform listing. Private. */
export interface CandidateSightingRow {
  id: string;
  candidate_id: string;
  source_id: string;
  /** The platform's own id. UNIQUE with source_id, so re-pulling is idempotent. */
  external_id: string;
  /** The listing page ON the platform -- what W9 comments on, not the product site. */
  source_url: string;
  title: string | null;
  author_handle: string | null;
  posted_at: Timestamp | null;
  /** Verbatim source payload for this item. Never edited. */
  raw: Record<string, unknown>;
  seen_at: Timestamp;
}

export type NewCandidateSighting = Pick<
  CandidateSightingRow,
  'candidate_id' | 'source_id' | 'external_id' | 'source_url'
> &
  Partial<Pick<CandidateSightingRow, 'title' | 'author_handle' | 'posted_at' | 'raw'>>;

/* ========================================================================== */
/* evidence                                                                    */
/* ========================================================================== */

/** What a fetched page is to us, so scoring can ask for the pricing page. */
export type EvidencePageRole =
  | 'homepage'
  | 'pricing'
  | 'docs'
  | 'api'
  | 'mcp'
  | 'changelog'
  | 'about'
  | 'blog'
  | 'repo'
  | 'robots_txt'
  | 'llms_txt'
  | 'other';

/** Something the page asserts. The left-hand side of the C1 diff. */
export interface EvidenceClaim {
  text: string;
  /** Where on the page it was found -- selector, heading, or section. */
  locator?: string;
}

/** A verbatim excerpt. Quoted, never paraphrased, so a score is auditable. */
export interface EvidenceQuote {
  text: string;
  locator?: string;
}

/** Measured behaviour rather than text: an endpoint responded, a schema parsed. */
export interface EvidenceObservation {
  kind: string;
  detail?: string;
  value?: string | number | boolean | null;
}

/**
 * A row of `finds_evidence`. Private, immutable and append-only -- a trigger
 * refuses UPDATE, DELETE and TRUNCATE for every caller, service role included,
 * because RLS cannot stop a role that bypasses RLS. Re-crawling appends a new
 * generation under a fresh `crawl_run_id`; it never overwrites.
 */
export interface EvidenceRow {
  id: string;
  candidate_id: string;
  /** Groups one crawl pass. Verdicts record which generation they scored. */
  crawl_run_id: string;
  url: string;
  page_role: EvidencePageRole;
  /** A 404 on /docs is evidence, not a missing row. */
  http_status: number | null;
  content_type: string | null;
  content_sha256: string | null;
  fetched_at: Timestamp;
  claims: EvidenceClaim[];
  quotes: EvidenceQuote[];
  observations: EvidenceObservation[];
  created_at: Timestamp;
}

export type NewEvidence = Pick<
  EvidenceRow,
  'candidate_id' | 'crawl_run_id' | 'url' | 'page_role'
> &
  Partial<
    Pick<
      EvidenceRow,
      'http_status' | 'content_type' | 'content_sha256' | 'fetched_at' | 'claims' | 'quotes' | 'observations'
    >
  >;

/* ========================================================================== */
/* verdicts                                                                    */
/* ========================================================================== */

/**
 * The four criteria.
 *   C1 what is advertised is actually true
 *   C2 solves a rare problem
 *   C3 usable by any person
 *   C4 agentic / MCP friendly
 */
export type Criterion = 'C1' | 'C2' | 'C3' | 'C4';

/**
 * How well the evidence supports the criterion. The scale is about evidential
 * support rather than about the product, which is what keeps one scale
 * meaningful across all four criteria.
 *   0 the evidence contradicts it
 *   1 no evidence either way
 *   2 partially supported
 *   3 clearly supported by quoted or measured evidence
 */
export type VerdictScore = 0 | 1 | 2 | 3;

/**
 * A row of `finds_verdicts`. Private.
 *
 * Insert one of these WITHOUT also inserting `finds_verdict_evidence` rows in
 * the same transaction and the COMMIT aborts: a deferred constraint trigger
 * enforces DECISIONS D7. `rationale` does not satisfy it -- prose is
 * supplementary to the citations, never a substitute.
 */
export interface VerdictRow {
  id: string;
  candidate_id: string;
  /** Which crawl generation was scored. Matches the cited rows' crawl_run_id. */
  evidence_run_id: string;
  criterion: Criterion;
  score: VerdictScore;
  rationale: string;
  /** Model id, or 'human'. Needed to compare rubric revisions honestly. */
  scored_by: string;
  created_at: Timestamp;
  updated_at: Timestamp;
}

export type NewVerdict = Pick<
  VerdictRow,
  'candidate_id' | 'evidence_run_id' | 'criterion' | 'score' | 'rationale' | 'scored_by'
>;

/** Contradicting evidence is a citation too: a score of 0 must point at it. */
export type CitationStance = 'supports' | 'contradicts';

/**
 * A row of `finds_verdict_evidence`. `candidate_id` is redundant on purpose --
 * it is what lets both foreign keys be composite, making a citation of another
 * product's evidence a foreign-key violation rather than a review catch.
 */
export interface VerdictEvidenceRow {
  verdict_id: string;
  evidence_id: string;
  candidate_id: string;
  stance: CitationStance;
  created_at: Timestamp;
}

export type NewVerdictEvidence = Pick<
  VerdictEvidenceRow,
  'verdict_id' | 'evidence_id' | 'candidate_id'
> &
  Partial<Pick<VerdictEvidenceRow, 'stance'>>;

/* ========================================================================== */
/* published finds -- the only public shape                                    */
/* ========================================================================== */

/**
 * One citation shown on the public page: the evidence behind a score, copied
 * out of `finds_evidence` at publish time rather than joined, because the
 * evidence table is private and must stay that way.
 */
export interface PublishedCitation {
  criterion: Criterion;
  url: string;
  /** Verbatim excerpt. Absent when the citation is a measured behaviour. */
  quote?: string;
  stance: CitationStance;
}

/**
 * A row of `finds_published` -- the ONLY anon-readable table in this
 * initiative (DECISIONS D8). W7 renders from this and nothing else.
 *
 * It is a snapshot, not a view. The browser holds the anon key, so anything
 * anon can select is public whether or not a page renders it; a join to
 * candidates, evidence and verdicts would either leak the private pipeline or
 * need a view that reads past RLS. It is also the honest editorial model: a
 * published find is what Nikhil approved on the day he approved it, and a later
 * re-crawl must not silently rewrite a page carrying his name.
 *
 * Rows with `published_at` null or in the future are invisible to anon, so a
 * draft cannot be read by asking for it directly.
 */
export interface PublishedFindRow {
  id: string;
  candidate_id: string;
  /** URL segment on the site: /interesting-finds/<slug> */
  slug: string;
  name: string;
  tagline: string | null;
  product_url: string;
  /** Platforms it was seen on. Appearing on three at once is part of the story. */
  source_labels: string[];
  found_at: Timestamp;
  published_at: Timestamp | null;
  /** C1: what is advertised is actually true. Same 0-3 scale as VerdictScore. */
  score_claim_verified: VerdictScore;
  /** C2: solves a rare problem. */
  score_rare_problem: VerdictScore;
  /** C3: usable by any person. */
  score_anyone_can_use: VerdictScore;
  /** C4: agentic / MCP friendly. */
  score_agentic_friendly: VerdictScore;
  /** Non-empty by CHECK: going public does not suspend D7. */
  citations: PublishedCitation[];
  /** Nikhil's own words, or null. Per D4 nothing generated goes here. */
  why_interesting: string | null;
  created_at: Timestamp;
  updated_at: Timestamp;
}

/**
 * What W7 actually receives. `published_at` is non-null for every row the anon
 * key can see, so the page never has to handle a draft.
 */
export type VisiblePublishedFind = Omit<PublishedFindRow, 'published_at'> & {
  published_at: Timestamp;
};

/* ========================================================================== */
/* digests                                                                     */
/* ========================================================================== */

/**
 * A digest cannot claim a delivery it did not get: `sent` requires `sent_at`
 * and `failed` requires `error`, both by CHECK. Per D2 and D6, W6 may not fake
 * a successful send.
 */
export type DigestStatus = 'pending' | 'sent' | 'failed';

/** A row of `finds_digests`. Private. */
export interface DigestRow {
  id: string;
  subject: string;
  recipient: string;
  status: DigestStatus;
  sent_at: Timestamp | null;
  /** Whatever the transport returned. Evidence a send really happened. */
  provider_message_id: string | null;
  /** Verbatim failure. Never a credential -- D2 forbids echoing the app password. */
  error: string | null;
  created_at: Timestamp;
  updated_at: Timestamp;
}

export type NewDigest = Pick<DigestRow, 'subject' | 'recipient'>;

/**
 * A row of `finds_digest_items`.
 *
 * `digest_status` is a trigger-maintained mirror of the parent digest's status
 * and must never be written by hand. It exists so "a candidate may appear in at
 * most one SENT digest" can be a partial unique index, which Postgres cannot
 * build across a join. The consequence that matters: a failed send does not
 * consume its candidates, so finds Nikhil never received are not lost.
 */
export interface DigestItemRow {
  digest_id: string;
  candidate_id: string;
  /** Order in the email, so the digest can be reconstructed exactly. */
  position: number;
  digest_status: DigestStatus;
  created_at: Timestamp;
}

export type NewDigestItem = Pick<DigestItemRow, 'digest_id' | 'candidate_id' | 'position'>;

/**
 * A row of the `finds_undigested_candidates` view: candidates not yet in a
 * successfully sent digest. Select from this rather than writing a NOT EXISTS
 * clause, so the never-twice rule lives in one place.
 */
export type UndigestedCandidateRow = CandidateRow;
