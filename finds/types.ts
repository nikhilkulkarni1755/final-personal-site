/* ========================================================================== */
/* finds_write_verdict -- the D7/D17 transaction bridge                        */
/* ========================================================================== */

/**
 * One citation as the RPC payload carries it. `stance` may be omitted and the
 * column default ('supports') applies.
 */
export interface WriteVerdictCitation {
  evidence_id: string;
  stance?: CitationStance;
}

/** One verdict as the RPC payload carries it. `citations` must be non-empty. */
export interface WriteVerdictPayload {
  criterion: Criterion;
  score: VerdictScore;
  rationale: string;
  scored_by: string;
  citations: WriteVerdictCitation[];
}

/**
 * Arguments for `supabase.rpc('finds_write_verdict', args)`.
 *
 * Why this exists rather than two inserts: D7's citation check is a
 * DEFERRABLE INITIALLY DEFERRED constraint trigger that fires at COMMIT, and
 * PostgREST gives one transaction per HTTP request (D17). Inserting the verdict
 * and then its citations commits the verdict alone, the trigger fires against
 * it uncited, and the transaction aborts -- correctly. One function call is one
 * transaction, so it can satisfy the constraint that two calls cannot.
 *
 * Every guarantee still holds at COMMIT: the deferred trigger runs, and both
 * `candidate_id` and `evidence_run_id` for each citation are taken from the
 * arguments rather than from the payload -- so the composite FKs make citing
 * another product's evidence, or evidence from a generation this score did not
 * read, impossible even if the payload asks for it.
 *
 * Service role only -- EXECUTE is revoked from anon and authenticated, because
 * PostgREST exposes every function as an endpoint and this one writes.
 */
export interface WriteVerdictArgs {
  p_candidate_id: string;
  p_evidence_run_id: string;
  /** Required. A defaulted version would stamp a rubric onto scores it did not produce. */
  p_rubric_version: string;
  p_verdicts: WriteVerdictPayload[];
}

/* ========================================================================== */
/* approvals -- the one thing that may cause a public page to appear (D29)     */
/* ========================================================================== */

/**
 * D9: Telegram is the control surface and the digest email is read-only. One
 * member on purpose, matching W11's `ApprovalChannel` -- an approval arriving
 * by any other route is not representable, in the type or in the CHECK.
 */
export type ApprovalChannel = 'telegram';

/**
 * A row of `finds_approvals`. Private, service-role only, and append-only: an
 * approval is a receipt for something a person said at a moment, and editing
 * one would rewrite the record of consent that a public page about someone
 * else's product rests on.
 *
 * A superset of W11's `FindApproval`, so a row can be handed straight to
 * `assertApprovedByNikhil()`. That check must keep running: this table is a
 * wider surface than a file, and the publish path should not trust that the
 * writer validated `chat_id`.
 *
 * AN APPROVAL ENABLES A PUBLISH; IT NEVER TRIGGERS ONE. Publishing is not a
 * scheduled stage and must not be called from `finds/run/**`. There is
 * deliberately no view listing approved-but-unpublished finds -- that query is
 * the missing ingredient for a cron that would turn a missed rejection into a
 * live page, so a publisher writes it by hand, naming the find.
 */
export interface ApprovalRow {
  id: string;
  candidate_id: string;
  /**
   * The verdict generation he actually saw. An approval floating free of a
   * generation would let a later re-score publish evidence he never read.
   * A composite FK makes approving an unscored generation impossible.
   */
  evidence_run_id: string;
  /** Pinned to 'C1'. Exists only to make that FK composite; never set it yourself. */
  approved_criterion: 'C1';
  channel: ApprovalChannel;
  /** Re-check this against TELEGRAM_CHAT_ID at read time. Always. */
  chat_id: string;
  /** Bot API message id of his answer -- the receipt. */
  message_id: number;
  /** Provenance only. `(chat_id, message_id)` is the replay key, not this. */
  telegram_update_id: number | null;
  /** Verbatim. Non-empty by CHECK: silence is not consent. */
  answer: string;
  /** Prose he wrote, or null. Per D4 nothing generated is ever written here. */
  why_interesting: string | null;
  answered_at: Timestamp;
  created_at: Timestamp;
}

/**
 * What W8's poller inserts.
 *
 * Write it with `ON CONFLICT (chat_id, message_id) DO NOTHING`. That unique key
 * absorbs a re-read of the same update after a runner restart, which is
 * precisely why the getUpdates offset does not also need to be durable for
 * publishing to be correct.
 */
export type NewApproval = Pick<
  ApprovalRow,
  'candidate_id' | 'evidence_run_id' | 'chat_id' | 'message_id' | 'answer' | 'answered_at'
> &
  Partial<Pick<ApprovalRow, 'channel' | 'telegram_update_id' | 'why_interesting'>>;

/* ========================================================================== */
/* HITL pending questions -- one store for asker and poller (D34)             */
/* ========================================================================== */

export type HitlPendingKind = 'plain' | 'approval';

/** One inline-keyboard button. */
export interface HitlPendingOption {
  label: string;
}

/**
 * A row of `finds_hitl_pending`. Private, service-role only.
 *
 * Unlike `ApprovalRow` and `EvidenceRow` this is MUTABLE and DELETABLE, and the
 * difference is principled rather than convenient: append-only guards a record
 * something else relies on as evidence. Nothing relies on a pending question
 * once it is answered -- the approval row is what W11 reads, and D29 settled
 * that rejections leave no trace. A resolved question is simply gone, so
 * "is there a row?" is the open/closed test and no reader has to remember a
 * `resolved_at` filter.
 */
export interface HitlPendingRow {
  /**
   * Caller-generated, with no database default. It is embedded in Telegram's
   * callback_data (`q:<id>:<idx>`) before the row exists, so a server-generated
   * id would produce a row that no tap could ever match.
   */
  id: string;
  chat_id: string;
  /** Bot API message id of the ask. A per-chat counter, hence unique with chat_id. */
  sent_message_id: number;
  prompt: string;
  context: string | null;
  /** NULL for a free-text-only ask. Required when `kind` is 'approval'. */
  options: HitlPendingOption[] | null;
  kind: HitlPendingKind;
  approval_candidate_id: string | null;
  approval_evidence_run_id: string | null;
  /** Pinned to 'C1'. Makes the FK composite; never set it yourself. */
  approval_criterion: 'C1' | null;
  /** Which option approves. Bounded against `options` by CHECK. */
  approve_option_index: number | null;
  /**
   * D32: free text is captured here, never acted on. Only an explicit tap
   * approves. Becomes `finds_approvals.why_interesting` if a later tap
   * approves. His prose verbatim -- per D4 nothing generated goes here.
   */
  draft_note: string | null;
  created_at: Timestamp;
}

/**
 * What the ask inserts. `id` is required because the caller minted it for the
 * callback_data. An 'approval' ask must supply the whole approval payload and
 * non-empty `options`; a half-filled one is refused by CHECK, and one naming an
 * unscored generation is a foreign-key violation.
 */
export type NewHitlPending = Pick<
  HitlPendingRow,
  'id' | 'chat_id' | 'sent_message_id' | 'prompt'
> &
  Partial<
    Pick<
      HitlPendingRow,
      | 'context'
      | 'options'
      | 'kind'
      | 'approval_candidate_id'
      | 'approval_evidence_run_id'
      | 'approval_criterion'
      | 'approve_option_index'
    >
  >;
